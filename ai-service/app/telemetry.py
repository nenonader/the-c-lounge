"""Per-turn telemetry for The C Lounge Private Concierge.

The v71 failure was not that Claude broke. It was that nobody could tell. A
scripted reply and a generated reply looked identical to a visitor, identical in
Firestore, and identical on /health. The site ran degraded for days.

Every turn now records which path served it, on which model, how long it took,
and why it fell back if it did. `/admin/turns` returns the recent buffer and the
Node backend writes the same record to Firestore, so the answer to "is the bot
actually thinking?" is one request away and permanently auditable.
"""

import time
from collections import deque
from typing import Deque, Dict, List

from . import config

COUNTERS: Dict[str, int] = {
    "turns_served": 0,
    "served_by_claude": 0,
    "served_by_fallback": 0,
    "envelope_parse_failures": 0,
    "outputs_refused": 0,
    "injection_blocked": 0,
    "sessions_locked": 0,
    "handoffs_ready": 0,
}

_TURNS: Deque[dict] = deque(maxlen=max(50, config.TELEMETRY_BUFFER))
LAST_FALLBACK_REASON = None


def record_turn(**fields) -> dict:
    """Store one turn record and bump the matching counters."""
    global LAST_FALLBACK_REASON
    record = {"at": time.time(), **fields}
    _TURNS.append(record)

    COUNTERS["turns_served"] += 1
    if record.get("served_by") == "claude":
        COUNTERS["served_by_claude"] += 1
    else:
        COUNTERS["served_by_fallback"] += 1
        LAST_FALLBACK_REASON = record.get("failure") or "unknown"
    if record.get("handoff_ready"):
        COUNTERS["handoffs_ready"] += 1
    return record


def bump(counter: str, amount: int = 1) -> None:
    COUNTERS[counter] = COUNTERS.get(counter, 0) + amount


def recent(limit: int = 50) -> List[dict]:
    return list(_TURNS)[-limit:]


def health_ratio() -> float:
    """Share of turns actually generated by Claude. 1.0 is a healthy service."""
    total = COUNTERS["turns_served"]
    return round(COUNTERS["served_by_claude"] / total, 3) if total else 1.0


def snapshot() -> dict:
    return {
        **COUNTERS,
        "claude_share": health_ratio(),
        "last_fallback_reason": LAST_FALLBACK_REASON,
    }
